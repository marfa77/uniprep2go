KEYS = "abcd"


def build(slug: str, rows: list[tuple[str, str, str, str, str, str, str]]) -> list[dict]:
    questions = []
    for index, (topic, prompt, correct, w1, w2, w3, why) in enumerate(rows):
        key = KEYS[index % 4]
        wrongs = [w1, w2, w3]
        options = []
        distractors: dict[str, str] = {}
        wi = 0
        for letter in KEYS:
            if letter == key:
                options.append({"id": letter, "text": correct})
            else:
                text = wrongs[wi]
                wi += 1
                options.append({"id": letter, "text": text})
                distractors[letter] = (
                    f"“{text}” does not answer “{prompt}”. That is a neighboring process, "
                    f"the drinking-water/electrical sibling, or an extreme never/always. "
                    f"The matching answer is: {correct}."
                )
        questions.append(
            {
                "id": f"{slug}-{topic}-{index + 1:03d}",
                "examSlug": slug,
                "topicId": topic,
                "prompt": prompt,
                "options": options,
                "correctOptionId": key,
                "explanation": (
                    f"{why} This item asks: “{prompt}”. The matching answer is: {correct}. "
                    "Independent UniPrep diagnostic — not an official NATE or state operator paper."
                ),
                "distractorExplanations": distractors,
                "difficulty": "medium",
                "sourceNote": "Ops P0 rewrite 2026-09-21: replaced sibling-remap bank with credential-matched items.",
            }
        )
    return questions


