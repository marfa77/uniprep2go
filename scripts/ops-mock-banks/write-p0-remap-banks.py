def main() -> None:
    nate = build("nate-core-readiness-check", NATE)
    ww = build("wastewater-operator-1-readiness-check", WASTEWATER)
    for slug, questions in (
        ("nate-core-readiness-check", nate),
        ("wastewater-operator-1-readiness-check", ww),
    ):
        if len(questions) != 60:
            raise SystemExit(f"{slug} has {len(questions)} questions")
        path = Path(f"/tmp/{slug}-fixed.json")
        path.write_text(json.dumps(questions, ensure_ascii=False, indent=2) + "\n")
        print(json.dumps({"slug": slug, "n": len(questions), "output": str(path)}))


if __name__ == "__main__":
    main()
