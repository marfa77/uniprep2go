def card_meta(card):
    topic = card[0]
    trap = len(card) > 7 and card[7] == "trap"
    return topic, trap


def rows(lang: str):
    idx = 0 if lang == "fr" else 1
    out = []
    for card in [INTRO, *CARDS]:
        topic, trap = card_meta(card)
        q_fr, a_fr, x_fr, q_en, a_en, x_en = card[1:7]
        q, a, x = (q_fr, a_fr, x_fr) if lang == "fr" else (q_en, a_en, x_en)
        out.append({
            "front": q,
            "back": a,
            "explanation": x,
            "topic": topic[idx],
            "module": MODULE[topic],
            "tags": " ".join(t for t in (f"module{MODULE[topic]}", TAG[topic], "piege" if trap else "") if t),
        })
    return out


def csv_rows(lang: str):
    """Legacy 5-column CSV (front,back,example,image_file,audio_file) for archive/diff."""
    return [
        {
            "front": r["front"],
            "back": r["back"],
            "example": f"{r['topic']} — {r['explanation']}" if r["explanation"] else r["topic"],
            "image_file": "",
            "audio_file": "",
        }
        for r in rows(lang)
    ]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--out-dir",
        default="/Users/pavelveselov/Projects/Anki Generator/out/prep2go_Luxembourg_Vivre_ensemble",
    )
    args = ap.parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for lang, name in (("fr", "source.csv"), ("en", "source_en.csv")):
        data = csv_rows(lang)
        fronts = [r["front"] for r in data]
        assert len(fronts) == len(set(fronts)), f"duplicate fronts in {lang}"
        assert all(r["example"] != r["example"].split(" — ")[0] or r is data[0] for r in data), "missing explanation"
        with open(out_dir / name, "w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["front", "back", "example", "image_file", "audio_file"])
            w.writeheader()
            w.writerows(data)
        print(f"{lang}: {len(data)} cards → {out_dir / name}")


if __name__ == "__main__":
    main()
